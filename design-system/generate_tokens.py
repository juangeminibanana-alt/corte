def camel(name: str) -> str:
    first, *rest = name.split("-")
    return first + "".join(part.capitalize() for part in rest)


def declaration(name: str, value: str) -> str:
    return f"  --cutgc-{name}: {value};"


def css_source(config: dict) -> str:
    fonts = config["font"]
    css_font = ", ".join(
        f'"{family}"' if " " in family else family
        for family in [fonts["web-family"], *fonts["css-fallbacks"]]
    )
    duration = config["motion"]["duration"]
    curve = ", ".join(map(str, config["motion"]["ease-exit"]))
    dark = [
        "  color-scheme: dark;",
        *(declaration(name, color) for name, color in config["themes"]["dark"].items()),
        declaration("elevation-overlay", config["elevation-overlay"]["dark"]),
    ]
    return "\n".join([
        "/* Generated by design-system/generate_tokens.py. Edit tokens.json. */",
        ":root {",
        "  color-scheme: light;",
        *(declaration(name, color) for name, color in config["themes"]["light"].items()),
        *(declaration(f"type-{role}", f"{size}px") for role, size in config["typography"].items()),
        *(declaration(f"space-{index}", f"{size}px") for index, size in config["spacing"].items()),
        *(declaration(f"radius-{name}", f"{size}px") for name, size in config["radii"].items()),
        declaration("elevation-overlay", config["elevation-overlay"]["light"]),
        *(declaration(f"duration-{name}", f"{ms}ms") for name, ms in duration.items()),
        declaration("ease-exit", f"cubic-bezier({curve})"),
        declaration("font-ui", css_font),
        declaration("font-display", fonts["display-family"] + ", " + css_font),
        "}", "",
        ':root[data-theme="dark"] {',
        *dark,
        "}", "",
        "@media (prefers-color-scheme: dark) {",
        '  :root[data-theme="system"] {',
        *(f"  {line}" for line in dark),
        "  }",
        "}", "",
        "@media (prefers-reduced-motion: reduce) {",
        "  :root {",
        *(f"  {declaration(f'duration-{name}', '0ms')}" for name in duration),
        "  }",
        "}",
        "",
    ])


def dart_source(config: dict) -> str:
    def color_declarations(colors: dict[str, str], prefix: str = "") -> list[str]:
        return [
            f"  static const {camel(prefix + key)} = Color(0xFF{hex_rgb.lstrip('#')});"
            for key, hex_rgb in colors.items()
        ]

    curve = ", ".join(map(str, config["motion"]["ease-exit"]))
    family = config["font"]["flutter-family"]
    return "\n".join([
        "// Generated by design-system/generate_tokens.py. Edit tokens.json.",
        "import 'package:flutter/material.dart';",
        "",
        "abstract final class CutgcDesignTokens {",
        *color_declarations(config["themes"]["light"]),
        "",
        *color_declarations(config["themes"]["dark"], "dark-"),
        "",
        *(f"  static const double {camel('type-' + key)} = {size};" for key, size in config["typography"].items()),
        *(f"  static const double space{index} = {size};" for index, size in config["spacing"].items()),
        *(f"  static const double {camel('radius-' + name)} = {size};" for name, size in config["radii"].items()),
        "",
        *(f"  static const {camel('duration-' + name)} = Duration(milliseconds: {ms});"
          for name, ms in config["motion"]["duration"].items()),
        f"  static const easeExit = Cubic({curve});",
        f"  static const fontFamily = '{family}';",
        f"  static const displayFontFamily = '{config['font']['display-family']}';",
        "}",
        "",
    ])


def android_colors(config: dict, theme: str) -> str:
    colors = {**config["themes"]["light"], **config["themes"][theme]}
    roles = ("canvas", "surface", "surface-raised", "line", "ink", "muted", "input-border",
             "action", "on-action", "chrome", "brand-coral", "brand-cyan")
    return "\n".join([
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!-- Generated by design-system/generate_tokens.py. -->',
        '<resources>',
        *(f'    <color name="cutgc_{role.replace("-", "_")}">{colors[role]}</color>' for role in roles),
        '</resources>', '',
    ])


def studio_entrance(config: dict) -> str:
    """Animate the master paths; keep the resting geometry identical to the signature."""
    svg = ET.parse(REPOSITORY / "spec/assets/logotipo.svg").getroot()
    diagonals, letters = svg.findall("{*}g")
    duration = config["motion"]["duration"]["intro"]
    motion = """
    .coral { animation: coral var(--intro) both }
    .cyan { animation: cyan var(--intro) both }
    .reveal { transform-origin: left center; animation: reveal var(--intro) both }
    @keyframes coral {
      0% { opacity: 0; transform: translate(-21px,39px) }
      6% { opacity: 1 }
      32%,100% { opacity: 1; transform: none }
    }
    @keyframes cyan {
      0%,5% { opacity: 0; transform: translate(21px,-39px) }
      10% { opacity: 1 }
      38%,100% { opacity: 1; transform: none }
    }
    @keyframes reveal {
      0%,22% { transform: scaleX(0) }
      51%,100% { transform: scaleX(1) }
    }
    @media (prefers-reduced-motion: reduce) {
      .coral,.cyan,.reveal { animation: none }
    }
    """
    lines = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{svg.attrib["viewBox"]}" role="img" aria-label="CUTGC">',
             '<title>CUTGC</title>',
             f'<style>:root {{ --intro: {duration}ms cubic-bezier(.2,.7,.1,1) }}{motion}</style>',
             '<defs><clipPath id="letras"><rect class="reveal" width="170" height="48" y="-3"/></clipPath></defs>']
    for name, path in zip(("coral", "cyan"), diagonals, strict=True):
        lines.append(f'<path class="{name}" fill="{path.attrib["fill"]}" d="{path.attrib["d"]}"/>')
    lines.append(f'<g transform="{letters.attrib["transform"]}"><g clip-path="url(#letras)">')
    for path in letters:
        lines.append(f'<path fill="{path.attrib["fill"]}" d="{path.attrib["d"]}"/>')
    lines.extend(['</g></g>', '</svg>', ''])
    return "\n".join(lines)


def native_wordmark() -> str:
    svg = ET.parse(REPOSITORY / "spec/assets/logotipo.svg").getroot()
    sign, letters = svg.findall("{*}g")
    x, y = letters.attrib["transform"].removeprefix("translate(").removesuffix(")").split()
    width, height = svg.attrib["viewBox"].split()[2:]
    drawing = [f'<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="130dp" android:height="24dp" android:viewportWidth="{width}" android:viewportHeight="{height}">']
    for path in sign:
        drawing.append(f'    <path android:fillColor="{path.attrib["fill"]}" android:pathData="{path.attrib["d"]}"/>')
    drawing.append(f'    <group android:translateX="{x}" android:translateY="{y}">')
    for path in letters:
        drawing.append(f'        <path android:fillColor="@color/cutgc_ink" android:pathData="{path.attrib["d"]}"/>')
    drawing.extend(['    </group>', '</vector>', ''])
    return "\n".join(drawing)


def hub_brand(config: dict) -> str:
    logo = (REPOSITORY / "spec/assets/logotipo.svg").read_text(encoding="utf-8").strip()
    roles = ("chrome", "ink", "muted", "canvas", "surface", "line", "success", "danger")
    def variables(theme: str) -> str:
        values = {**config["themes"]["light"], **config["themes"][theme]}
        return "".join(f"--{key}:{values[key]};" for key in roles)
    css = ":root{" + variables("light") + "}@media(prefers-color-scheme:dark){:root{" + variables("dark") + "}}"
    return "# Generated by design-system/generate_tokens.py.\n" + f"MARCA = {logo!r}\nTEMA = {css!r}\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report out-of-date tokens and guide assets.")
    args = parser.parse_args()
    config = json.loads((HERE / "tokens.json").read_text(encoding="utf-8"))
    targets = {
        HERE / "tokens.css": css_source(config),
        HERE / "assets/entrada-estudio.svg": studio_entrance(config),
        REPOSITORY / "client_flutter/lib/ui/design_tokens.g.dart": dart_source(config),
    }
    targets[REPOSITORY / "hub/creatorhub/identidad_generada.py"] = hub_brand(config)
    targets[REPOSITORY / "client_flutter/android/app/src/main/res/drawable/cutgc_firma.xml"] = native_wordmark()
    for theme, folder in (("light", "values"), ("dark", "values-night")):
        for app in ("android", "client_flutter/android"):
            resources = REPOSITORY / app / "app/src/main/res" / folder
            targets[resources / "cutgc_design.xml"] = android_colors(config, theme)
    outdated = []
    for path, generated in targets.items():
        if path.is_file() and path.read_text(encoding="utf-8") == generated:
            continue
        if args.check:
            outdated.append(path.relative_to(REPOSITORY).as_posix())
        else:
            path.parent.mkdir(exist_ok=True, parents=True)
            path.write_text(generated, encoding="utf-8", newline="\n")
    for filename, source in GUIDE_ASSETS.items():
        path = HERE / "assets" / filename
        original = (REPOSITORY / source).read_bytes()
        if path.is_file() and path.read_bytes() == original:
            continue
        if args.check:
            outdated.append(path.relative_to(REPOSITORY).as_posix())
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_bytes(original)
    if outdated:
        print("Regenerate design tokens and guide assets: " + ", ".join(outdated))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
