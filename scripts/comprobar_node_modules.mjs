#!/usr/bin/env node
/**
 * Corte · ¿ui/node_modules coincide con ui/package-lock.json? (build-empaquetado; lo usa scripts/comun_empaquetado.ps1)
 *
 *   node scripts/comprobar_node_modules.mjs <carpeta ui>
 *
 * Coincide si (1) cada paquete del lock está instalado con la versión exacta del lock (los opcionales de otra
 * plataforma, que npm no instala, se omiten) y (2) no hay en node_modules un paquete de primer nivel que el lock no
 * tenga. Sale con 0 si coincide, 1 si no (dice por qué, hasta 8 motivos) y 2 si falta el lock o node_modules.
 *
 * Para qué: AsegurarNodeModules (scripts/comun.ps1) corre `npm ci` cuando falta la marca .ch-lock.sha256, y `npm ci`
 * BORRA node_modules antes de instalar. En el árbol compartido (varios paquetes trabajando a la vez) eso tumba las
 * pruebas de los demás aunque node_modules ya esté al día. Con esta comprobación, la marca solo se adopta cuando
 * node_modules ya corresponde al lock; si no, `npm ci` corre igual que siempre.
 */
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ui = resolve(process.argv[2] ?? '.');
const rutaLock = join(ui, 'package-lock.json');
const nm = join(ui, 'node_modules');
if (!existsSync(rutaLock)) {
  console.error(`comprobar_node_modules: falta ${rutaLock}`);
  process.exit(2);
}
if (!existsSync(nm)) {
  console.error(`comprobar_node_modules: falta ${nm}`);
  process.exit(2);
}

const lock = JSON.parse(readFileSync(rutaLock, 'utf8'));
if (![2, 3].includes(lock.lockfileVersion) || typeof lock.packages !== 'object') {
  console.error(`comprobar_node_modules: lockfileVersion ${lock.lockfileVersion} no soportado (se esperaba 2 o 3)`);
  process.exit(2);
}

const motivos = [];
let revisados = 0;
for (const [clave, info] of Object.entries(lock.packages)) {
  if (!clave || info.link) continue;                              // raíz del proyecto y enlaces de espacio de trabajo
  const pj = join(ui, ...clave.split('/'), 'package.json');
  if (!existsSync(pj)) {
    if (info.optional || info.devOptional || info.inBundle) continue;   // opcional de otra plataforma: npm no lo instala
    motivos.push(`falta ${clave}`);
    continue;
  }
  let instalado;
  try {
    instalado = JSON.parse(readFileSync(pj, 'utf8')).version;
  } catch (e) {
    motivos.push(`${clave}/package.json ilegible (${e.message})`);
    continue;
  }
  if (instalado !== info.version) motivos.push(`${clave}: instalado ${instalado}, lock ${info.version}`);
  revisados++;
}

// Paquetes de primer nivel (y @alcance/paquete) que el lock no conoce: los dejaría `npm ci` fuera.
for (const nombre of readdirSync(nm)) {
  if (nombre.startsWith('.')) continue;                           // .bin, .package-lock.json, .ch-lock.sha256, cachés
  const hijos = nombre.startsWith('@') ? readdirSync(join(nm, nombre)).map((h) => `${nombre}/${h}`) : [nombre];
  for (const h of hijos) {
    if (!lock.packages[`node_modules/${h}`]) motivos.push(`sobra node_modules/${h} (no está en el lock)`);
  }
}

if (motivos.length) {
  console.log(`comprobar_node_modules: NO coincide (${motivos.length}): ${motivos.slice(0, 8).join(' · ')}${motivos.length > 8 ? ' · …' : ''}`);
  process.exit(1);
}
console.log(`comprobar_node_modules: coincide · ${revisados} paquetes del lock instalados con su versión exacta`);
